function hiddenUnless(templates: string[]) {
  return ({document}: {document?: unknown}) => {
    const template =
      document &&
      typeof document === 'object' &&
      'template' in document &&
      typeof document.template === 'string'
        ? document.template
        : ''
    if (!template) return false
    return !templates.includes(template)
  }
}

